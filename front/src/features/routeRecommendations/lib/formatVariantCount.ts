import { pluralize } from '@shared/lib';

/**
 * Число подобранных вариантов вместе с согласованным словом: «5 вариантов».
 *
 * Живёт рядом с самой подборкой, а не на странице: счёт вариантов подписывает
 * и ряд на маршруте, и ленту, и обе подписи должны меняться вместе.
 */
export const formatVariantCount = (count: number): string =>
    pluralize(count, ['вариант', 'варианта', 'вариантов']);
