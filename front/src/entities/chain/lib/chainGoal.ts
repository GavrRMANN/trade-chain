import type { TChain } from '../types';

/**
 * Цель, к которой относится цепочка.
 *
 * Категория опережает товар назначения: у предложения внутри маршрута к
 * категории заполнены оба поля — конкретный товар нужен, чтобы обмен вообще
 * мог состояться, а категория говорит, куда идёт путь. Прямое предложение
 * цели не имеет, и его собственный товар назначения работает как цель из
 * одного шага.
 */
export const getChainGoalId = (chain: TChain): string | undefined =>
    chain.exchange_goal_id ?? chain.to_category_id ?? chain.to_product_id;

/**
 * Относится ли обмен к цепочке (персональному маршруту к цели).
 *
 * Признак — именно привязка к цели: без неё предложение самостоятельное, и
 * товар назначения целью не считается, иначе цепочкой оказался бы каждый
 * прямой обмен.
 */
export const isRouteChain = (chain: TChain): boolean =>
    Boolean(chain.exchange_goal_id ?? chain.to_category_id);
