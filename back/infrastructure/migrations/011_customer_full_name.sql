-- ФИО участника.
--
-- До сих пор человек на площадке был виден только по email: и в карточке
-- товара, и в переписке по обмену собеседник представлен адресом почты.
-- Для обмена вещами это плохо — договариваются о встрече с человеком, а не
-- с почтовым ящиком.
--
-- Колонка не обязательная: идентификатором остаётся email, ФИО — то, что
-- видит вторая сторона. Пустая строка вместо NULL, чтобы в запросах не
-- появлялось COALESCE, а в Go — указатель ради значения по умолчанию.
--
-- Миграцию безопасно прогнать повторно.

ALTER TABLE customers
    ADD COLUMN IF NOT EXISTS full_name VARCHAR(255) NOT NULL DEFAULT '';

-- ---------- ФИО демо-аккаунтов ----------

-- Аккаунты из 006 заведены до появления колонки. Бэкфилл идёт здесь, а не в
-- самом 006: тот файл генерируется из front/mock-api/data.js и на пустой базе
-- выполняется раньше этой миграции — колонки в момент INSERT ещё нет.
--
-- Сопоставление по email, а не по customer_id: адрес в mock-данных стабилен,
-- а uuid пересчитывается из строкового ключа при каждой перегенерации.
--
-- Условие full_name = '' оставляет нетронутыми имена, которые пользователь
-- уже поменял сам: повторный прогон миграции их не откатит.
UPDATE customers AS c
SET full_name = seed.full_name
FROM (VALUES
    ('alexey@example.com',  'Ковалёв Алексей Игоревич'),
    ('maria@example.com',   'Соколова Мария Андреевна'),
    ('ivan@example.com',    'Морозов Иван Петрович'),
    ('olga@example.com',    'Лебедева Ольга Сергеевна'),
    ('dmitry@example.com',  'Волков Дмитрий Николаевич'),
    ('elena@example.com',   'Зайцева Елена Викторовна'),
    ('sergey@example.com',  'Новиков Сергей Дмитриевич'),
    ('natalia@example.com', 'Егорова Наталья Олеговна'),
    ('pavel@example.com',   'Титов Павел Романович'),
    ('irina@example.com',   'Крылова Ирина Максимовна'),
    ('roman@example.com',   'Богданов Роман Алексеевич')
) AS seed(email, full_name)
WHERE c.email = seed.email
  AND c.full_name = '';

-- ---------- индексы под сводку участников ----------

-- Сводка считает товары и цепочки подзапросами на каждого участника.
-- По products(customer_id) индекс есть с 001, по chains — только на
-- initiator_id и recipient_id по отдельности, чего для условия
-- «инициатор ИЛИ получатель» достаточно: планировщик берёт оба через
-- BitmapOr. Отдельного индекса под статус товара не хватает — активные
-- отбираются в паре с владельцем.
CREATE INDEX IF NOT EXISTS idx_products_customer_status
    ON products(customer_id, status);
